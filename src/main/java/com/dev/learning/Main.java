public class Main{
    public static void main(String[] args){
        System.out.println("Switch case");
        int i = 13;
        switch(i){
            case 1:
                System.out.println("This is 1");
                break;
            case 2:
                System.out.println("This is 2");
                break;
            case 3:
                System.out.println("This is 3");
                break;
            default:
                System.out.println("This is default");
        }
    }
}